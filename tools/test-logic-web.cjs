const {chromium}=require('playwright');
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
(async()=>{
 const out=path.resolve('artifacts/streaming');
 fs.mkdirSync(path.join(out,'downloads'),{recursive:true});
 const browser=await chromium.launch({headless:true,channel:'msedge',downloadsPath:path.join(out,'downloads')});
 const context=await browser.newContext({viewport:{width:1600,height:1100},deviceScaleFactor:1,acceptDownloads:true});
 const page=await context.newPage();const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 try {
  await page.goto('http://127.0.0.1:8765/');
  await page.waitForFunction(()=>document.getElementById('connection').textContent.includes('已连接'));
  assert.equal(await page.locator('.channel-row').count(),8);
  await page.screenshot({path:path.join(out,'web-ready.png'),fullPage:true});
  await page.locator('#legacy').click();
  await page.waitForFunction(()=>document.getElementById('statSamples').textContent==='262,144');
  await page.waitForTimeout(200);
  await page.screenshot({path:path.join(out,'web-history.png'),fullPage:true});
  await page.locator('#zoomIn').click();
  const box=await page.locator('#wave').boundingBox();
  await page.mouse.click(box.x+box.width*.3,box.y+100);
  await page.keyboard.down('Shift');await page.mouse.click(box.x+box.width*.7,box.y+100);await page.keyboard.up('Shift');
  await page.waitForFunction(()=>document.getElementById('cursorReadout').textContent.includes('Δ'));
  const downloadPromise=page.waitForEvent('download');await page.locator('#exportCsv').click();
  const download=await downloadPromise;await download.saveAs(path.join(out,'downloads','checked-edges.csv'));
  assert(fs.readFileSync(path.join(out,'downloads','checked-edges.csv'),'utf8').includes('CH7'));
  await page.locator('#seconds').selectOption('5');await page.locator('#start').click();
  await page.waitForFunction(()=>document.getElementById('liveTag').textContent==='采集中');
  await page.waitForFunction(limit=>Number(document.getElementById('statSamples').textContent.replaceAll(',',''))>limit,process.env.WEB_STRESS==='1'?40000000:500000);
  await page.screenshot({path:path.join(out,'web-live.png'),fullPage:true});
  await page.locator('#stop').click();
  await page.waitForFunction(()=>document.getElementById('start').disabled===false,{timeout:15000});
  assert.equal(await page.locator('#integrity').textContent(),'传输校验通过');
  await page.waitForTimeout(500);
  assert.equal(await page.locator('#exportLas').isDisabled(),false);
  await page.locator('#records').click();
  await page.locator('#recordList button').first().waitFor();
  const captureState=await(await page.request.get('http://127.0.0.1:8765/api/state')).json();
  await page.locator('#encoding').selectOption('0');await page.locator('#seconds').selectOption('1');await page.locator('#start').click();
  await page.waitForFunction(()=>document.getElementById('integrity').textContent==='异常 · flags=8');
  await page.screenshot({path:path.join(out,'web-overflow.png'),fullPage:true});
  await page.locator('#encoding').selectOption('1');await page.locator('#start').click();
  await page.waitForFunction(()=>document.getElementById('integrity').textContent==='传输校验通过');
  await page.setViewportSize({width:390,height:844});await page.waitForTimeout(100);
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:path.join(out,'web-mobile.png'),fullPage:true});
  await page.locator('#toggleSettings').click();assert(await page.locator('#settings').isVisible());
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(out,'browser-test.json'),JSON.stringify({passed:true,errors,captureState},null,2));
  console.log('BROWSER_TEST_PASSED',JSON.stringify(captureState));
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
